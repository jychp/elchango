def generated_header(document: dict[str, Any]) -> str:
    canonical = json.dumps(
        document,
        ensure_ascii=True,
        separators=(",", ":"),
        sort_keys=True,
    ).encode()
    digest = hashlib.sha256(canonical).hexdigest()
    return (
        "Generated by scripts/generate_http_contracts.py from "
        f"contracts/http/v1/openapi.json (sha256: {digest})."
    )


def load_source() -> dict[str, Any]:
    document = json.loads(SOURCE.read_text())
    if document.get("openapi") != "3.1.0":
        raise ValueError("contract source must use OpenAPI 3.1.0")
    paths = document.get("paths", {})
    forbidden = {"/api/focus", "/api/intent"} & paths.keys()
    if forbidden:
        raise ValueError(f"removed paths are present: {sorted(forbidden)}")
    return document


def schemas(document: dict[str, Any]) -> dict[str, Any]:
    return document["components"]["schemas"]


def enum_values(all_schemas: dict[str, Any], name: str) -> list[str]:
    values = all_schemas[name].get("enum")
    if not isinstance(values, list) or not all(isinstance(value, str) for value in values):
        raise ValueError(f"{name} must be a string enum")
    return values


def swift_case(value: str) -> str:
    if value == "create_pr":
        return "createPR"
    pieces = re.split(r"[-_]", value)
    candidate = pieces[0] + "".join(piece.capitalize() for piece in pieces[1:])
    if candidate == "default":
        return "`default`"
    return candidate


def swift_enum(name: str, values: list[str]) -> str:
    cases = []
    for value in values:
        case = swift_case(value)
        suffix = "" if case == value else f' = "{value}"'
        cases.append(f"    case {case}{suffix}")
    return (
        f"public enum {name}: String, Codable, Sendable {{\n"
        + "\n".join(cases)
        + "\n}"
    )


