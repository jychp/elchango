def generated(document: dict[str, Any]) -> dict[Path, str]:
    return {
        SWIFT_OUTPUT: render_swift(document),
        WEB_OUTPUT: render_typescript(document, web=True),
        STREAMDECK_OUTPUT: render_typescript(document, web=False),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail if generated files differ instead of writing them",
    )
    args = parser.parse_args()
    expected = generated(load_source())
    stale = [
        path
        for path, content in expected.items()
        if not path.exists() or path.read_text() != content
    ]
    if args.check:
        if stale:
            for path in stale:
                print(f"stale generated contract: {path.relative_to(ROOT)}", file=sys.stderr)
            print("run: python3 scripts/generate_http_contracts.py", file=sys.stderr)
            return 1
        print("generated HTTP contracts are current")
        return 0
    for path, content in expected.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
